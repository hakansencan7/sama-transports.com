(()=>{"use strict";
const gallery=document.getElementById("iw-gallery");
const lightbox=document.getElementById("iw-gallery-lightbox");
if(!gallery||!lightbox)return;
const items=[...gallery.querySelectorAll(".iw-gallery-item")];
const viewer=lightbox.querySelector(".iw-lightbox-image");
const closeBtn=lightbox.querySelector(".iw-lightbox-close");
const prevBtn=lightbox.querySelector(".iw-lightbox-previous");
const nextBtn=lightbox.querySelector(".iw-lightbox-next");
const count=lightbox.querySelector(".iw-lightbox-count");
let current=0,touchX=null,lastFocus=null;
const render=()=>{const img=items[current].querySelector("img");viewer.src=img.currentSrc||img.src;viewer.alt=img.alt;count.textContent=`${current+1} / ${items.length}`;};
const open=i=>{current=i;lastFocus=document.activeElement;render();lightbox.classList.add("is-open");lightbox.setAttribute("aria-hidden","false");document.body.style.overflow="hidden";closeBtn.focus();};
const close=()=>{lightbox.classList.remove("is-open");lightbox.setAttribute("aria-hidden","true");document.body.style.overflow="";viewer.removeAttribute("src");if(lastFocus&&typeof lastFocus.focus==="function")lastFocus.focus();};
const move=d=>{current=(current+d+items.length)%items.length;render();};
items.forEach((item,i)=>item.addEventListener("click",()=>open(i)));
closeBtn.addEventListener("click",close);
prevBtn.addEventListener("click",()=>move(-1));
nextBtn.addEventListener("click",()=>move(1));
lightbox.addEventListener("click",e=>{if(e.target===lightbox)close();});
document.addEventListener("keydown",e=>{if(!lightbox.classList.contains("is-open"))return;if(e.key==="Escape")close();else if(e.key==="ArrowLeft")move(-1);else if(e.key==="ArrowRight")move(1);});
viewer.addEventListener("touchstart",e=>{touchX=e.changedTouches[0].clientX;},{passive:true});
viewer.addEventListener("touchend",e=>{if(touchX===null)return;const dx=e.changedTouches[0].clientX-touchX;if(Math.abs(dx)>45)move(dx>0?-1:1);touchX=null;},{passive:true});
})();